  <script>
    function toggleGallery(className, btn) {
      let images = document.querySelectorAll("." + className);
      let isHidden = images[0].style.display === "none" || images[0].style.display === "";

      images.forEach(img => {
        img.style.display = isHidden ? "block" : "none";
      });

      btn.innerHTML = isHidden
        ? 'Show Less <span class="arrow">⬆</span>'
        : 'View More <span class="arrow">⬇</span>';
    }
